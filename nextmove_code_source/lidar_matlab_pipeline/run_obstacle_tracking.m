%% =====================================================================
%% NextMove: 2-D obstacle tracking from frame-wise obstacle detections
%% NN data association + constant-velocity Kalman Filter, no deep learning.
%% =====================================================================
clear; clc; close all;

workspaceRoot = fileparts(mfilename("fullpath"));
detectionResultsFolder = fullfile(workspaceRoot, "obstacle_detection_results");
trackingResultsFolder = fullfile(workspaceRoot, "obstacle_tracking_results");

if ~isfolder(trackingResultsFolder)
    mkdir(trackingResultsFolder);
end

detectionFiles = dir(fullfile(detectionResultsFolder, "nextmove_obstacle_list_*.csv"));
if isempty(detectionFiles)
    error("No obstacle detection CSV was found in: %s", detectionResultsFolder);
end

[~, newestIdx] = max([detectionFiles.datenum]);
detectionCsv = fullfile(detectionFiles(newestIdx).folder, detectionFiles(newestIdx).name);

fprintf("Loading detections: %s\n", detectionCsv);
obstacleTable = readtable(detectionCsv, 'TextType', 'string');
fprintf("Loaded %d detection rows across %d frames.\n", ...
    height(obstacleTable), numel(unique(obstacleTable.frameId)));

%% Tracking parameters
trackingOptions = struct( ...
    "FramePeriod", 0.1, ...
    "ProcessNoise", 3.0, ...
    "MeasurementNoise", 0.45, ...
    "AssociationGate", 7.0, ...
    "MaxAssociationDistance", 2.5, ...
    "MaxMissedFrames", 8, ...
    "MinHitsToConfirm", 2, ...
    "MaxSpeed", 25.0, ...
    "RiskHighDistance", 6.0, ...
    "RiskMediumDistance", 12.0, ...
    "RiskCorridorHalfWidth", 2.2, ...
    "RiskHighTTC", 2.5, ...
    "RiskMediumTTC", 5.0);

fprintf("Running 2-D NN + Kalman tracking...\n");
[trackedTable, trackHistory] = trackObstacles2D( ...
    obstacleTable, ...
    "FramePeriod", trackingOptions.FramePeriod, ...
    "ProcessNoise", trackingOptions.ProcessNoise, ...
    "MeasurementNoise", trackingOptions.MeasurementNoise, ...
    "AssociationGate", trackingOptions.AssociationGate, ...
    "MaxAssociationDistance", trackingOptions.MaxAssociationDistance, ...
    "MaxMissedFrames", trackingOptions.MaxMissedFrames, ...
    "MinHitsToConfirm", trackingOptions.MinHitsToConfirm, ...
    "MaxSpeed", trackingOptions.MaxSpeed, ...
    "RiskHighDistance", trackingOptions.RiskHighDistance, ...
    "RiskMediumDistance", trackingOptions.RiskMediumDistance, ...
    "RiskCorridorHalfWidth", trackingOptions.RiskCorridorHalfWidth, ...
    "RiskHighTTC", trackingOptions.RiskHighTTC, ...
    "RiskMediumTTC", trackingOptions.RiskMediumTTC);

timestamp = string(datetime("now", "Format", "yyyyMMdd_HHmmss"));
trackedCsv = fullfile(trackingResultsFolder, "nextmove_tracked_obstacle_list_" + timestamp + ".csv");
summaryCsv = fullfile(trackingResultsFolder, "nextmove_tracking_summary_" + timestamp + ".csv");
matFile = fullfile(trackingResultsFolder, "nextmove_obstacle_tracking_" + timestamp + ".mat");

trackingSummary = buildTrackingSummary(trackedTable);

writetable(trackedTable, trackedCsv);
writetable(trackingSummary, summaryCsv);
save(matFile, ...
    "trackedTable", "trackingSummary", "trackHistory", ...
    "trackingOptions", "detectionCsv", "-v7.3");

fprintf("\nTracking finished.\n");
fprintf("Tracked obstacle CSV: %s\n", trackedCsv);
fprintf("Tracking summary CSV: %s\n", summaryCsv);
fprintf("MAT results: %s\n", matFile);

disp("Summary:");
disp(trackingSummary);

function trackingSummary = buildTrackingSummary(trackedTable)
if isempty(trackedTable)
    trackingSummary = table(0, 0, 0, 0, 0, ...
        'VariableNames', {'numFrames', 'numTrackRows', 'numTracks', ...
        'numConfirmedRows', 'numHighRiskRows'});
    return;
end

trackingSummary = table( ...
    numel(unique(trackedTable.frameId)), ...
    height(trackedTable), ...
    numel(unique(trackedTable.trackId)), ...
    sum(trackedTable.isConfirmed), ...
    sum(trackedTable.riskLevel == "HIGH"), ...
    'VariableNames', {'numFrames', 'numTrackRows', 'numTracks', ...
    'numConfirmedRows', 'numHighRiskRows'});
end
